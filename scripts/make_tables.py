"""Generate markdown + LaTeX tables from results/<sweep>_long.csv and _runs.csv (never typed by hand).

  python scripts/make_tables.py [--sweep main] [--aggregate]

Statistic: for each (model, regime, exp, split, seed) take the mean of the metric over the split's
N values; then report mean ± std (ddof=1) and median over seeds, plus the number of seeds.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from nlse_ml.eval import aggregate  # noqa: E402
from nlse_ml.viz.style import MODELS  # noqa: E402

SPLIT_ORDER = ["train", "interp", "near", "far", "extrap"]


def seed_stats(long, metric):
    d = long[long.metric == metric]
    per_seed = d.groupby(["model", "regime", "exp", "split", "seed", "tag"], dropna=False)["value"].mean().reset_index()
    g = per_seed.groupby(["model", "regime", "exp", "split", "tag"], dropna=False)["value"]
    return g.agg(mean="mean", std=lambda x: x.std(ddof=1) if len(x) > 1 else np.nan, median="median",
                 n="count").reset_index()


def fmt(r, pct):
    f = 100.0 if pct else 1.0
    s = f"{r['mean'] * f:.2f}" if pct else f"{r['mean']:.2e}"
    if r["n"] > 1:
        s += f" ± {r['std'] * f:.2f}" if pct else f" ± {r['std']:.1e}"
    return s


def table(long, regime, exp, metric="rel_l2", pct=True, tag=""):
    st = seed_stats(long, metric)
    st = st[(st.regime == regime) & (st.exp == exp) & (st.tag.fillna("") == tag)]
    if st.empty:
        return None, None
    splits = [s for s in SPLIT_ORDER if s in set(st.split)]
    models = [m for m in MODELS if m in set(st.model)]
    unit = " (%)" if pct else ""
    md = [f"| Model | " + " | ".join(f"{s}{unit}" for s in splits) + " | seeds |",
          "|---|" + "---|" * (len(splits) + 1)]
    tex = [r"\begin{tabular}{l" + "c" * (len(splits) + 1) + "}", r"\toprule",
           "Model & " + " & ".join(splits) + r" & seeds \\", r"\midrule"]
    for m in models:
        cells, nmax = [], 0
        for s in splits:
            r = st[(st.model == m) & (st.split == s)]
            if r.empty:
                cells.append("–")
                continue
            r = r.iloc[0]
            nmax = max(nmax, int(r["n"]))
            cells.append(fmt(r, pct) + f" (med {r['median'] * (100 if pct else 1):.2f})" if pct else fmt(r, pct))
        md.append(f"| {MODELS[m][0]} | " + " | ".join(cells) + f" | {nmax} |")
        tex.append(MODELS[m][0] + " & " + " & ".join(c.replace("±", r"$\pm$") for c in cells) + f" & {nmax} \\\\")
    tex += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(md), "\n".join(tex)


def cost_table(runs):
    if runs.empty:
        return ""
    g = runs.groupby(["model"]).agg(train_min=("train_wall_s", lambda x: np.median(x) / 60),
                                    peak_mem_gb=("peak_mem_gb", "median"), steps=("steps_done", "median"),
                                    params=("n_params", "median"), infer_ms=("inference_s_per_field",
                                                                             lambda x: 1e3 * np.median(x)),
                                    n_runs=("status", "count"),
                                    n_failed=("status", lambda x: int((x != "ok").sum())))
    md = ["| Model | median train (min) | peak GPU mem (GB) | optimizer steps | params | inference (ms/field) | runs | failed |",
          "|---|---|---|---|---|---|---|---|"]
    for m in [m for m in MODELS if m in g.index]:
        r = g.loc[m]
        md.append(f"| {MODELS[m][0]} | {r.train_min:.1f} | {r.peak_mem_gb:.2f} | {int(r.steps)} | {int(r.params)} | "
                  f"{r.infer_ms:.1f} | {int(r.n_runs)} | {int(r.n_failed)} |")
    return "\n".join(md)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sweep", default="main")
    ap.add_argument("--aggregate", action="store_true", help="re-scan runs/ first")
    ap.add_argument("--tag", default="", help="only runs with this tag (e.g. pilot tags)")
    a = ap.parse_args()
    if a.aggregate:
        aggregate.write(a.sweep)
    long = pd.read_csv(ROOT / "results" / f"{a.sweep}_long.csv")
    runs = pd.read_csv(ROOT / "results" / f"{a.sweep}_runs.csv")
    out = ROOT / "report" / "tables"
    out.mkdir(parents=True, exist_ok=True)
    doc = [f"# Results tables ({a.sweep})", "",
           "Generated by `scripts/make_tables.py` from `results/`. Relative L2 of the complex field over the "
           "evaluated (xi, tau) grid, in %. Per seed: mean over the split's N values; cells show mean ± std over "
           "seeds (median in brackets).", ""]
    for regime in ["A", "B_sech", "B_gauss"]:
        for exp in ["n_extrap", "z_extrap"]:
            for metric, pct in [("rel_l2", True), ("rel_l2_intensity", True), ("phase_err", False), ("spectral_err", True), ("energy_drift_max", False)]:
                md, tex = table(long, regime, exp, metric, pct, a.tag)
                if md is None:
                    continue
                name = f"{a.sweep}{'_' + a.tag if a.tag else ''}_{regime}_{exp}_{metric}"
                (out / f"{name}.md").write_text(md + "\n", encoding="utf-8")
                (out / f"{name}.tex").write_text(tex + "\n", encoding="utf-8")
                doc += [f"## {regime} / {exp} / {metric}", "", md, ""]
    runs = runs[runs.tag.fillna("") == a.tag]
    doc += ["## Cost", "", cost_table(runs), ""]
    name = f"{a.sweep}_{a.tag}_all.md" if a.tag else f"{a.sweep}_all.md"
    (out / name).write_text("\n".join(doc), encoding="utf-8")
    print("\n".join(doc))


if __name__ == "__main__":
    main()
